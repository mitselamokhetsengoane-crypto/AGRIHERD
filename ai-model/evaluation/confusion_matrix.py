"""
Confusion Matrix Generator for AgriHerd AI Model
=================================================
Generates and saves a confusion matrix showing which classes
the model correctly identifies vs. confuses.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from model_loader import load_model


def generate_confusion_matrix(data_yaml_path: str = None):
    """
    Generate confusion matrix from model evaluation.
    
    The confusion matrix is saved as an image in the same directory.
    """
    if data_yaml_path is None:
        possible_paths = [
            os.path.join(os.path.dirname(__file__), "../../dataset/data.yaml"),
            os.path.join(os.path.dirname(__file__), "../../multicrop_clean/multicrop_clean/data.yaml"),
        ]
        for path in possible_paths:
            if os.path.exists(path):
                data_yaml_path = path
                break

    if not data_yaml_path or not os.path.exists(data_yaml_path):
        raise FileNotFoundError("data.yaml not found.")

    model = load_model()
    print("🔍 Running evaluation to generate confusion matrix...")

    metrics = model.val(data=data_yaml_path, plots=True)

    # Ultralytics automatically saves the confusion matrix to runs/detect/val*/
    print("\n✅ Confusion matrix generated by Ultralytics.")
    print("   Look in: runs/detect/val*/confusion_matrix.png")
    print("   Copy this file to your report for evidence.")

    return metrics


if __name__ == "__main__":
    generate_confusion_matrix()